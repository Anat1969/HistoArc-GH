const { chromium } = require('playwright');
const SP = process.argv[2]; // folder with a local copy of ai-menu.js
const ok = (c, m) => console.log(c ? 'ok  ' : 'FAIL', m);
(async () => {
  const b = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-webgl', '--ignore-gpu-blocklist'] });
  const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
  await ctx.route('https://appofapp-gh.vercel.app/ai-menu.js', (r) => r.fulfill({ path: SP + '/ai-menu.js', contentType: 'text/javascript' }));
  const p = await ctx.newPage();
  const errs = []; p.on('pageerror', (e) => errs.push(e.message));
  let n = 0; p.on('dialog', (d) => d.accept(d.type() === 'prompt' ? ['חלופה רחוב', 'חלופה מגדלים'][n++] : undefined));
  await p.goto('http://localhost:4173/#/'); await p.waitForTimeout(2500);
  await p.screenshot({ path: SP + '/u-home.png' });
  ok((await p.textContent('h1')).includes('אילו בחירות'), 'home shows the research question');
  await p.click('text=התחל: בחנו את אשדוד'); await p.waitForTimeout(4500);
  ok((await p.textContent('.lens .q')).includes('התרחיש'), 'scenario question in lab');
  await p.screenshot({ path: SP + '/u-lab.png' });
  ok(await p.locator('text=לפני ואחרי').isVisible(), 'before/after visible');
  await p.click('text=שמור כחלופה'); await p.waitForTimeout(500);
  ok(await p.locator('text=נשמר: חלופה רחוב').isVisible(), 'saved 1');
  await p.selectOption('select[aria-label="תרחיש מוסבר"]', 's-ashdod-tower'); await p.waitForTimeout(4500);
  await p.click('text=שמור כחלופה'); await p.waitForTimeout(500);
  ok(await p.locator('text=נשמר: חלופה מגדלים').isVisible(), 'saved 2');
  await p.click('.tabs button:has-text("על המפה")'); await p.waitForTimeout(1500);
  ok(await p.locator('.maplibregl-map').count() > 0, 'map mounted');
  await p.screenshot({ path: SP + '/u-map.png' });
  await p.goto('http://localhost:4173/#/alts'); await p.waitForTimeout(800);
  const boxes = p.locator('input[type=checkbox]');
  ok((await boxes.count()) === 2, 'two alternatives listed after navigation');
  await boxes.nth(0).check(); await boxes.nth(1).check(); await p.waitForTimeout(3000);
  await p.screenshot({ path: SP + '/u-alts.png' });
  await p.click('text=הפק השוואה מנומקת'); await p.waitForTimeout(1000);
  ok((await p.textContent('.doc-view')).includes('הפשרה המרכזית'), 'compare output generated');
  await p.screenshot({ path: SP + '/u-out.png' });
  await p.click('button:has-text("עריכה")'); await p.fill('textarea.doc', '# בדיקה ערוכה\nטקסט'); await p.click('button:has-text("שמירה")');
  await p.reload(); await p.waitForTimeout(1500);
  await p.goto('http://localhost:4173/#/out'); await p.waitForTimeout(800);
  ok(await p.locator('text=השוואת חלופות').first().isVisible(), 'output persists after reload');
  await p.locator('aside section:last-child button').first().click(); await p.waitForTimeout(500);
  ok((await p.textContent('.doc-view')).includes('בדיקה ערוכה'), 'edit persisted');
  await p.goto('http://localhost:4173/#/people'); await p.waitForTimeout(1500);
  await p.screenshot({ path: SP + '/u-people.png' });
  await p.click('a:has-text("לבחון על אשדוד")'); await p.waitForTimeout(4000);
  ok((await p.textContent('.lens .q')).includes('כך הייתה הגישה'), 'person reading opens lab');
  console.log('errors', errs);
  await b.close();
})();
